// 사건 id는 events-data.js의 id와 같아야 한다.

function c(member, title, date, source, content) {
  return { member: member, title: title, date: date, source: source, content: content };
}

function addComments(eventId, list) {
  const ev = EVENT_BY_ID[eventId];
  if (!ev) { console.error("소감을 연결할 사건이 없음:", eventId); return; }
  list.forEach(function (item) { ev.comments.push(item); });
}

